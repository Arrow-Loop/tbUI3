// Turns tbIDE/WinUI3IdeStyle/css/winui3-ide.css and winui3-ide-icons.css (written by build-toolbar-icons.mjs)
// into tbIDE/WinUI3IdeStyle/src/Sources/WinUI3IdeCss.twin.
// Usage: node build-addin-css.mjs [cssFile[,cssFile...]] [twinFile]   (defaults are the paths above, relative to this script)
// Then patch the project: node tools/twinproj-src.mjs patch tbIDE/WinUI3IdeStyle/WinUI3IdeStyle.twinproj tbIDE/WinUI3IdeStyle/src Sources/WinUI3IdeCss.twin
//
// Comments are dropped and each rule becomes one line of the string Build() returns, so the add-in can
// compare RuleCount() with the number of rules the browser parsed. Long rules are split over several
// twinBASIC lines (the string itself stays one CSS line). The CSS must not contain double quotes
// (twinBASIC strings would need Chr(34)) or nested blocks such as @media; the script stops if it does.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const cssFiles = process.argv[2] ? process.argv[2].split(',')
  : ['winui3-ide.css', 'winui3-ide-icons.css'].map(f => path.join(here, '../WinUI3IdeStyle/css', f));
const twinFile = process.argv[3] || path.join(here, '../WinUI3IdeStyle/src/Sources/WinUI3IdeCss.twin');
const MaxChunk = 180;

const fail = msg => { console.error('build-addin-css: ' + msg); process.exit(1); };
const cssFile = cssFiles.join(', ');
const source = cssFiles.map(f => fs.readFileSync(f, 'utf8')).join('\n');
const css = source.replace(/\/\*[\s\S]*?\*\//g, ' ');
if (css.includes('"')) fail('double quote found; use single quotes in ' + cssFile);
if (css.includes('/*') || css.includes('*/')) fail('unbalanced comment');

// Split into top-level rules and reject nesting.
const rules = [];
let depth = 0, start = 0;
for (let i = 0; i < css.length; i++) {
  const c = css[i];
  if (c === '{') { depth++; if (depth > 1) fail('nested block near: ' + css.slice(start, i).trim().slice(0, 60)); }
  else if (c === '}') {
    depth--; if (depth < 0) fail('unbalanced }');
    rules.push(css.slice(start, i + 1)); start = i + 1;
  }
}
if (depth !== 0 || css.slice(start).trim()) fail('text after the last rule or unclosed block');

const tidy = r => {
  r = r.replace(/\s+/g, ' ').trim();
  const open = r.indexOf('{');
  const selector = r.slice(0, open).trim().replace(/\s*,\s*/g, ', ');
  const body = r.slice(open + 1, -1).trim().split(';').map(d => d.trim()).filter(Boolean).join('; ');
  if (!/^(body\b)/.test(selector) || selector.split(', ').some(s => !/^body\b/.test(s))) fail('selector not prefixed with body: ' + selector);
  return selector + ' { ' + body + '; }';
};
const lines = rules.map(tidy);

// Split a rule into chunks no longer than MaxChunk, preferring to break after "; " or ", ".
const chunks = line => {
  const out = [];
  while (line.length > MaxChunk) {
    let cut = Math.max(line.lastIndexOf('; ', MaxChunk), line.lastIndexOf(', ', MaxChunk));
    if (cut < 40) cut = MaxChunk; else cut += 2;
    out.push(line.slice(0, cut)); line = line.slice(cut);
  }
  out.push(line);
  return out;
};

const rel = p => path.relative(path.join(here, '..', '..'), p).split(path.sep).join('/');
const out = [];
out.push('Module WinUI3IdeCss');
out.push('    \' GENERATED by tbIDE/tools/build-addin-css.mjs from ' + cssFiles.map(rel).join(' and ') + '.');
out.push('    \' Do not edit here: change the .css files (they carry the WinUI token names and sources for every rule) and run the script.');
out.push('    \' The stylesheet the add-in puts on the IDE page while a WinUI3 theme is active, one CSS rule per line.');
out.push('');
out.push('    \' Number of rules Build() returns. The add-in\'s log compares it with what the browser parsed.');
out.push('    Public Function RuleCount() As Long');
out.push('        Return ' + lines.length);
out.push('    End Function');
out.push('');
out.push('    Public Function Build() As String');
out.push('        Dim css As String');
for (const line of lines) {
  const parts = chunks(line);
  parts.forEach((p, i) => out.push('        css = css & "' + p + '"' + (i === parts.length - 1 ? ' & vbCrLf' : '')));
}
out.push('        Return css');
out.push('    End Function');
out.push('');
out.push('End Module');
fs.writeFileSync(twinFile, out.join('\r\n') + '\r\n');

// Also write the exact text Build() returns, for browser tests.
if (process.env.ADDIN_CSS_OUT) fs.writeFileSync(process.env.ADDIN_CSS_OUT, lines.join('\r\n') + '\r\n');
console.log(`build-addin-css: ${lines.length} rules, ${lines.join('\r\n').length + 2 * lines.length} characters -> ${rel(twinFile)}`);

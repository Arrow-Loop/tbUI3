// Generate the embedded script from the readable adapter. No loose JS is needed after build.
import fs from 'node:fs';
import path from 'node:path';
import { edit } from '../../tools/twinproj-edit.mjs';
const dir = 'tbIDE/tbUI3IDE';
const file = dir + '/tbUI3IDE.twinproj';
if (!fs.existsSync(file)) throw new Error('The canonical unified add-in project is required.');
const wrapper = dir + '/src/Sources/TabViewDesignerController.twin';
fs.writeFileSync(wrapper, fs.readFileSync(wrapper, 'utf8').replace(/\r?\n/g, '\r\n'));
const js = fs.readFileSync(dir + '/js/tabview-designer.js', 'utf8').trim();
const names = ['getCurrentFormEditorGlobals','preparePaste','deserializeControls',
    'prepareForMultipleChangeProperties','handleMultipleChangeProperties','doPaste',
    'getTopLeftOfAllControls','changedSelectedControls','unselectAllControls','changeProperty',
    'undoPoint','getImageFromServer','queueMultipleSnapshot','syncPropertySheet','deleteSelectedControls','updateAllControlDragPoints','lockTheControl','unlockTheControl','onSignificantChange'];
const facade = '{document:document,setInterval:setInterval.bind(window),clearInterval:clearInterval.bind(window),' +
    names.map(n => n + ':typeof ' + n + "==='function'?" + n + ':undefined').join(',') + '}';
const script = "(function(){if(window.__tbUI3TabDesigner)window.__tbUI3TabDesigner.dispose();" +
    'window.__tbUI3TabDesigner=' + js + '(' + facade + ');return window.__tbUI3TabDesigner.install()})()';
// Chr(34), rather than doubled quotes, represents quotes in twinBASIC source.
const literal = s => s.split('"').map(s => '"' + s + '"').join(' & Chr(34) & ');
const lines = ['\' Generated by tbIDE/tools/build-tabview-designer.mjs. Edit js/tabview-designer.js.',
    'Private Module TabViewDesignerScript','    Public Function Build() As String','        Dim js As String'];
// Line comments in the adapter need actual newlines in the assembled JavaScript.
// Cap source-line length and append explicit vbLf after each original line.
for (const line of script.split(/\r?\n/)) {
    for (let i=0; i<line.length; i+=150) lines.push('        js = js & ' + literal(line.slice(i,i+150)));
    lines.push('        js = js & vbLf');
}
lines.push('        Return js','    End Function','End Module','');
fs.writeFileSync(dir + '/src/Sources/TabViewDesignerScript.twin', lines.join('\r\n'));
if (fs.existsSync(file)) {
    const { scan } = await import('../../tools/twinproj-edit.mjs');
    let binary = fs.readFileSync(file), entries = scan(binary);
    const replace = {}, add = {};
    for (const rel of ['Settings',...fs.readdirSync(dir+'/src/Sources').map(f=>'Sources/'+f)]) {
        const data = fs.readFileSync(path.join(dir,'src',rel));
        (entries[rel] ? replace : add)[rel] = data;
    }
    binary = edit(binary,{replace,add});
    fs.writeFileSync(file,binary);
}
console.log('TabView Designer script generated (' + script.length + ' characters)');

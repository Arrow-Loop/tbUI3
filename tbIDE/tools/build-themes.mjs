function render(name, rows) {
  const out = [
    '/*',
    `    ${name} for the twinBASIC IDE (built for BETA 1043).`,
    '    Colours are WinUI 3 theme resources (Common_themeresources_any.xaml in microsoft-ui-xaml),',
    '    the same tokens WinUI Gallery uses. Accent colours assume the default Windows blue accent.',
    '    Generated by tbIDE-theme/tools/build-themes.mjs; edit that script, not this file.',
    '*/',
    '',
  ];
  const seen = new Set();
  for (const r of rows) {
    if (typeof r === 'string') { out.push('', r); continue; }
    const [k, v, note] = r;
    if (seen.has(k)) throw new Error(`${name}: duplicate ${k}`);
    seen.add(k);
    if (/: |;\s|;$/.test(v)) throw new Error(`${name}: value for ${k} would break the IDE parser`);
    const line = (k + ':').padEnd(44) + v + ';';
    out.push(note && !v.startsWith('url(') ? line.padEnd(96) + ' /* ' + note + ' */' : line);
  }
  return out.join('\r\n') + '\r\n';
}


// Writes tbIDE/WinUI3IdeStyle/css/winui3-ide-icons.css: one rule per toolbar button that sets --fluent-icon
// to a Fluent UI System Icon, which winui3-ide.css draws as a mask filled with the text colour.
// Usage: node build-toolbar-icons.mjs [--refresh <@fluentui/svg-icons icons folder>]
//   --refresh copies the icons named below from an unpacked @fluentui/svg-icons package into
//   tbIDE/WinUI3IdeStyle/icons/fluent/ first. Without it the committed copies are used.
// Then run build-addin-css.mjs, which reads winui3-ide.css and this file.
//
// Icons: Fluent UI System Icons, MIT License, Copyright (c) 2020 Microsoft Corporation
// (https://github.com/microsoft/fluentui-system-icons). See icons/fluent/LICENSE.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const iconDir = path.join(here, '../WinUI3IdeStyle/icons/fluent');
const cssFile = path.join(here, '../WinUI3IdeStyle/css/winui3-ide-icons.css');

// Toolbar element id (main.htm #rootMenu2) -> Fluent icon file (name_size_regular.svg).
// 16px artwork is used where the set has it; the rest are 20px artwork drawn at 16px.
// Comment, uncomment, indent, outdent and the form designer's align and size buttons keep the IDE's own
// glyphs (Shane, 2026-11-09): they show what each command does better than the Fluent set.
const map = [
  ['saveIcon', 'save_16_regular'],
  ['searchIcon', 'document_search_16_regular'],
  ['designSwitchIcon', 'arrow_swap_16_regular'],
  ['undoIcon', 'arrow_undo_16_regular'],
  ['redoIcon', 'arrow_redo_16_regular'],
  ['playIcon', 'play_16_filled'],
  ['pauseIcon', 'pause_16_regular'],
  ['stopIcon', 'stop_16_filled'],
  ['debugStepOverIcon', 'arrow_step_over_16_regular'],
  ['debugStepIntoIcon', 'arrow_step_in_16_regular'],
  ['debugStepOutIcon', 'arrow_step_out_16_regular'],
  ['restartIcon', 'arrow_clockwise_16_regular'],
  ['trashIcon', 'broom_16_regular'],
  ['buildIcon', 'box_arrow_up_20_regular'],
  ['menuBarGrid', 'grid_dots_16_regular'],
  ['menuBarBringToFront', 'position_to_front_20_regular'],
  ['menuBarSendToBack', 'position_to_back_20_regular'],
  ['menuBarPreview', 'window_play_20_regular'],
  ['menuBarColorMode', 'dark_theme_20_regular'],
];

const fail = msg => { console.error('build-toolbar-icons: ' + msg); process.exit(1); };
const refresh = process.argv.indexOf('--refresh');
if (refresh >= 0) {
  const from = process.argv[refresh + 1] || fail('--refresh needs the icons folder');
  fs.mkdirSync(iconDir, { recursive: true });
  for (const [, icon] of map) fs.copyFileSync(path.join(from, icon + '.svg'), path.join(iconDir, icon + '.svg'));
}

// SVG -> data URI with no double quotes (the add-in's twinBASIC strings) and no raw single quotes
// (the url('...') wrapper). The fill colour is irrelevant: only the mask's alpha is used.
const dataUri = svg => {
  svg = svg.trim().replace(/"/g, "'").replace(/\s+/g, ' ');
  return 'data:image/svg+xml,' + encodeURIComponent(svg).replace(/'/g, '%27').replace(/%20/g, ' ')
    .replace(/%3D/g, '=').replace(/%3A/g, ':').replace(/%2F/g, '/').replace(/%2C/g, ',');
};

const out = [
  '/* GENERATED by tbIDE/tools/build-toolbar-icons.mjs. Do not edit here: change the map in the script and run it. */',
  '/* Toolbar icons: Fluent UI System Icons, MIT License, Copyright (c) 2020 Microsoft Corporation. */',
  '/* https://github.com/microsoft/fluentui-system-icons (see ../icons/fluent/LICENSE) */',
  '',
];
for (const [id, icon] of map) {
  const file = path.join(iconDir, icon + '.svg');
  if (!fs.existsSync(file)) fail('missing ' + file + ' (run with --refresh <icons folder>)');
  const uri = dataUri(fs.readFileSync(file, 'utf8'));
  if (uri.includes('"') || uri.includes("'")) fail('quote left in ' + icon);
  out.push(`/* ${icon} */`);
  out.push(`body #rootMenu2 > #${id} { --fluent-icon: url('${uri}'); }`);
}
fs.writeFileSync(cssFile, out.join('\n') + '\n');
console.log(`build-toolbar-icons: ${map.length} icons -> ${path.relative(path.join(here, '..', '..'), cssFile).split(path.sep).join('/')}`);

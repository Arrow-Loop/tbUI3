import fs from 'node:fs';
const dir='tbIDE/tbUI3IDE';
const bootstrap=fs.readFileSync(dir+'/js/shutdown-bridge.js','utf8').trim();
const literal=s=>s.split('"').map(x=>'"'+x+'"').join(' & Chr(34) & ');
const lines=["' Generated by tbIDE/tools/build-updater-script.mjs.",'Private Module UpdaterScript','    Public Function Build() As String','        Dim js As String'];
for(const line of bootstrap.split(/\r?\n/)){for(let i=0;i<line.length;i+=150)lines.push('        js = js & '+literal(line.slice(i,i+150)));lines.push('        js = js & vbLf');}
lines.push('        Return js','    End Function','End Module','');
fs.writeFileSync(dir+'/src/Sources/UpdaterScript.twin',lines.join('\r\n'));
console.log('Embedded shutdown bridge: '+bootstrap.length+' characters');

